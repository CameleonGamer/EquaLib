void eq_display_draw_string(const char* text, eadk_point_t point,
                            bool large_font, eadk_color_t text_color,
                            eadk_color_t background_color) {
    if (!text) return;
    int cur_x = point.x;
    int cur_y = point.y;
    int scale = large_font ? 2 : 1;
    int cell_w = 6 * scale;
    int cell_h = 8 * scale;

    while (*text) {
        unsigned char ch = (unsigned char)*text++;
        if (ch == '\n') {
            cur_x = point.x;
            cur_y += cell_h + 2;
            continue;
        }

        /* Decodage des caracteres accentues UTF-8 francais courants */
        if (ch == 0xC3 && *text) {
            unsigned char next = (unsigned char)*text++;
            if (next >= 0xA8 && next <= 0xAB) ch = 'e'; /* e, e, e, e */
            else if (next >= 0x88 && next <= 0x8B) ch = 'E';
            else if (next >= 0xA0 && next <= 0xA5) ch = 'a'; /* a, a, a, a, a, a */
            else if (next >= 0xAC && next <= 0xAF) ch = 'i'; /* i, i, i, i */
            else if (next >= 0xB2 && next <= 0xB6) ch = 'o'; /* o, o, o, o, o */
            else if (next >= 0xB9 && next <= 0xBC) ch = 'u'; /* u, u, u, u */
            else if (next == 0xA7) ch = 'c'; /* c */
            else ch = '?';
        }

        if (ch < 32 || ch > 126) {
            ch = '?';
        }

        if (cur_x >= EADK_SCREEN_WIDTH || cur_y >= EADK_SCREEN_HEIGHT) {
            break;
        }

        const uint8_t* glyph = s_font6x8[ch - 32];

        if (scale == 1) {
            int draw_w = (cur_x + 6 <= EADK_SCREEN_WIDTH) ? 6 : (EADK_SCREEN_WIDTH - cur_x);
            int draw_h = (cur_y + 8 <= EADK_SCREEN_HEIGHT) ? 8 : (EADK_SCREEN_HEIGHT - cur_y);
            if (draw_w > 0 && draw_h > 0) {
                eadk_color_t buf[8 * 6];
                for (int r = 0; r < draw_h; r++) {
                    uint8_t row_bits = glyph[r];
                    for (int c = 0; c < draw_w; c++) {
                        buf[r * draw_w + c] = (row_bits & (0x20 >> c)) ? text_color : background_color;
                    }
                }
                eadk_display_push_rect((eadk_rect_t){(uint16_t)cur_x, (uint16_t)cur_y, (uint16_t)draw_w, (uint16_t)draw_h}, buf);
            }
        } else {
            int draw_w = (cur_x + 12 <= EADK_SCREEN_WIDTH) ? 12 : (EADK_SCREEN_WIDTH - cur_x);
            int draw_h = (cur_y + 16 <= EADK_SCREEN_HEIGHT) ? 16 : (EADK_SCREEN_HEIGHT - cur_y);
            if (draw_w > 0 && draw_h > 0) {
                eadk_color_t buf[16 * 12];
                for (int r = 0; r < draw_h; r++) {
                    uint8_t row_bits = glyph[r / 2];
                    for (int c = 0; c < draw_w; c++) {
                        buf[r * draw_w + c] = (row_bits & (0x20 >> (c / 2))) ? text_color : background_color;
                    }
                }
                eadk_display_push_rect((eadk_rect_t){(uint16_t)cur_x, (uint16_t)cur_y, (uint16_t)draw_w, (uint16_t)draw_h}, buf);
            }
        }

        cur_x += cell_w;
    }
}
