void ui_clear_screen(eadk_color_t color) {
  eadk_rect_t screen = {0, 0, EADK_SCREEN_WIDTH, EADK_SCREEN_HEIGHT};
  eadk_display_push_rect_uniform(screen, color);
}

void ui_draw_rect(int x, int y, int w, int h, eadk_color_t color) {
  if (x < 0 || y < 0 || w <= 0 || h <= 0) return;
  eadk_rect_t rect = {(int16_t)x, (int16_t)y, (int16_t)w, (int16_t)h};
  eadk_display_push_rect_uniform(rect, color);
}

void ui_draw_rect_outline(int x, int y, int w, int h, eadk_color_t color) {
  ui_draw_rect(x, y, w, 1, color);
  ui_draw_rect(x, y + h - 1, w, 1, color);
  ui_draw_rect(x, y, 1, h, color);
  ui_draw_rect(x + w - 1, y, 1, h, color);
}

void ui_draw_char(int x, int y, char c, eadk_color_t fg, eadk_color_t bg) {
  if (c < 32 || c > 126) c = '?';
  const uint8_t * col = font5x7[(uint8_t)c];
  
  eadk_color_t buffer[6 * 8];
  for (int row = 0; row < 8; row++) {
    for (int c_idx = 0; c_idx < 5; c_idx++) {
      bool pixel_on = (row < 7) && ((col[c_idx] >> row) & 1);
      buffer[row * 6 + c_idx] = pixel_on ? fg : bg;
    }
    buffer[row * 6 + 5] = bg; // Espace inter-caractères
  }

  eadk_rect_t r = {(int16_t)x, (int16_t)y, 6, 8};
  eadk_display_push_rect(r, buffer);
}

void ui_draw_string(int x, int y, const char * text, eadk_color_t fg, eadk_color_t bg) {
  int cur_x = x;
  while (*text) {
    if (cur_x + 6 > EADK_SCREEN_WIDTH) break;
    ui_draw_char(cur_x, y, *text, fg, bg);
    cur_x += 6;
    text++;
  }
}

void ui_draw_status_bar(const char * title, bool exam_mode_active) {
  // Bandeau supérieur style NumWorks
  eadk_color_t bar_color = exam_mode_active ? EADK_COLOR_NUMWORKS : EADK_COLOR_GRAY_DARK;
  eadk_color_t text_color = exam_mode_active ? EADK_COLOR_BLACK : EADK_COLOR_WHITE;

  ui_draw_rect(0, 0, EADK_SCREEN_WIDTH, STATUS_BAR_HEIGHT, bar_color);

  // Titre centré
  int title_len = (int)strlen(title);
  int title_x = (EADK_SCREEN_WIDTH - (title_len * 6)) / 2;
  ui_draw_string(title_x, 5, title, text_color, bar_color);

  // Logo / Cadenas Mode Examen si actif
  if (exam_mode_active) {
    ui_draw_string(8, 5, "[EXAM]", EADK_COLOR_RED, bar_color);
  } else {
    ui_draw_string(8, 5, "EquaLib", text_color, bar_color);
  }

  // Indicateur batterie simulé
  ui_draw_rect(EADK_SCREEN_WIDTH - 24, 6, 16, 7, text_color);
  ui_draw_rect(EADK_SCREEN_WIDTH - 8, 8, 2, 3, text_color);
  ui_draw_rect(EADK_SCREEN_WIDTH - 22, 8, 12, 3, bar_color);
}

void ui_draw_default_icon(int x, int y, const char * initial, bool selected) {
  eadk_color_t bg = selected ? EADK_COLOR_NUMWORKS : EADK_COLOR_GRAY_LIGHT;
  eadk_color_t border = selected ? EADK_COLOR_BLACK : EADK_COLOR_GRAY_DARK;

  // Corps de l'icône (55x56 pixels)
  ui_draw_rect(x, y, ICON_WIDTH, ICON_HEIGHT, bg);
  ui_draw_rect_outline(x, y, ICON_WIDTH, ICON_HEIGHT, border);

  // Lettre initiale au centre
  char buf[2] = {initial[0], '\0'};
  ui_draw_string(x + (ICON_WIDTH / 2) - 3, y + (ICON_HEIGHT / 2) - 4, buf, EADK_COLOR_BLACK, bg);
}

void ui_draw_app_grid(const equalib_header_t * header, const equalib_app_entry_t * apps, int selected_index) {
  int start_x = 30;
  int start_y = 35;
  int gap_x = 45;
  int gap_y = 40;

  int count = (header && header->app_count > 0) ? (int)header->app_count : 0;

  for (int i = 0; i < count; i++) {
    int col = i % GRID_COLS;
    int row = i / GRID_COLS;
    if (row >= GRID_ROWS) break;

    int x = start_x + col * (ICON_WIDTH + gap_x);
    int y = start_y + row * (ICON_HEIGHT + gap_y);
    bool selected = (i == selected_index);

    // Dessin de l'icône
    ui_draw_default_icon(x, y, apps[i].name, selected);

    // Nom sous l'icône (centré)
    int name_len = (int)strlen(apps[i].name);
    int text_x = x + (ICON_WIDTH / 2) - (name_len * 6 / 2);
    if (text_x < 5) text_x = 5;
    
    ui_draw_string(text_x, y + ICON_HEIGHT + 4, apps[i].name, EADK_COLOR_TEXT, EADK_COLOR_WHITE);

    // Cadre de sélection accentué si sélectionné
    if (selected) {
      ui_draw_rect_outline(x - 3, y - 3, ICON_WIDTH + 6, ICON_HEIGHT + 6, EADK_COLOR_NUMWORKS);
      ui_draw_rect_outline(x - 2, y - 2, ICON_WIDTH + 4, ICON_HEIGHT + 4, EADK_COLOR_BLACK);
    }
  }

  // Barre d'instructions en bas
  ui_draw_rect(0, EADK_SCREEN_HEIGHT - 16, EADK_SCREEN_WIDTH, 16, EADK_COLOR_GRAY_LIGHT);
  ui_draw_string(10, EADK_SCREEN_HEIGHT - 12, "OK: Lancer  |  Back x2: Simuler Examen", EADK_COLOR_TEXT, EADK_COLOR_GRAY_LIGHT);
}
